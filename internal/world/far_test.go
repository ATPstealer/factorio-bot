package world

import (
	"testing"

	"factorio-bot/internal/bridge"
)

// Грубый путь в обход воды: по суше, без срезания углов; на остров — нет.
func TestFarPath(t *testing.T) {
	w := grid(t,
		"................................",
		"................................",
		"................................",
		"................................",
		"................................",
		"................................",
		"................................",
		"................................",
		"................................",
		"................................",
		"wwwwwwwwwwwwwwwwwwwwwwwwwwwwwww.",
		"................................",
		"................................",
		"................................",
		"................................",
		"................................",
		"................................",
		"................................",
		"................................",
		"................................",
		"...........wwwww................",
		"...........w...w................",
		"...........w...w................",
		"...........wwwww................",
	)
	from, to := bridge.Pos{X: 5.5, Y: 5.5}, bridge.Pos{X: 5.5, Y: 15.5}
	r, ok := w.FarPath(from, to)
	if !ok {
		t.Fatal("пути в обход воды нет")
	}
	if r.Points[0] != from || r.Points[len(r.Points)-1] != to {
		t.Errorf("концы пути %v … %v", r.Points[0], r.Points[len(r.Points)-1])
	}
	for i := 1; i < len(r.Points); i++ {
		a, b := r.Points[i-1], r.Points[i]
		n := int(dist(a, b)/0.1) + 1
		for j := 0; j <= n; j++ {
			f := float64(j) / float64(n)
			if q := (bridge.Pos{X: a.X + (b.X-a.X)*f, Y: a.Y + (b.Y-a.Y)*f}); w.TileAt(TileOf(q)) == Water {
				t.Fatalf("отрезок %v → %v идёт по воде у %v", a, b, q)
			}
		}
	}
	if l := r.Length(); l < 50 {
		t.Errorf("путь %.1f тайлов — не в обход (прямая 10)", l)
	}
	if _, ok := w.FarPath(from, bridge.Pos{X: 13.5, Y: 21.5}); ok {
		t.Error("путь на остров")
	}
}
